//! CA public keys for the 券面 applications' card-verifiable certificates.
//!
//! A card-verifiable certificate names its signing key by 証明者鍵ID and does not carry it, so a
//! verifier has to hold the CA keys itself. These are the ones in circulation.
//!
//! To use a key you obtained yourself instead, pass it to
//! [`CardVerifiableCertificate::verify_with`](crate::data::CardVerifiableCertificate::verify_with).
//!
//! # Coverage
//!
//! Three production keys — `"5000020"`, `"5000023"` and `"5000033"` — and the three matching
//! keys of the test hierarchy JPKI test cards are issued under. Anything else answers
//! [`Error::UnknownCertificateAuthority`](crate::Error::UnknownCertificateAuthority) — nothing was
//! checked — rather than failing the signature.
//!
//! Every 証明者鍵ID seen on any card examined resolves; the intermediates below them need no
//! entry, since each one's key travels inside the certificate above it.

use crate::data::{KeyId, RsaPublicKey};

/// A CA public key, with the 証明者鍵ID that names it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CaKey {
    /// 証明者鍵ID, 16 bytes — what a certificate's `issuer_key_id` is matched against.
    pub key_id: &'static [u8; 16],
    /// Modulus, big-endian.
    pub modulus: &'static [u8],
    /// Public exponent, big-endian. 65537 for every key here.
    pub exponent: &'static [u8],
}

impl CaKey {
    /// The key in the form the rest of this crate uses.
    pub fn to_public_key(&self) -> RsaPublicKey {
        RsaPublicKey {
            exponent: self.exponent.to_vec(),
            modulus: self.modulus.to_vec(),
        }
    }

    /// The printable part of the 証明者鍵ID, for messages.
    pub fn name(&self) -> &str {
        std::str::from_utf8(&self.key_id[..7]).unwrap_or("?")
    }
}


/// Look up a CA key by 証明者鍵ID.
///
/// The identifier is compared in full, all 16 bytes, so a certificate from a different hierarchy
/// does not match a production key by accident.
pub fn find(key_id: &KeyId) -> Option<&'static CaKey> {
    KNOWN.iter().find(|k| k.key_id == key_id.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_entry_is_a_well_formed_rsa_2048_key() {
        assert!(!KNOWN.is_empty());
        for key in KNOWN {
            assert_eq!(key.modulus.len(), 256, "{} is not RSA-2048", key.name());
            assert_eq!(key.exponent, E65537);
            // The identifier is one of the 16 byte references: 7 digits, 08 05, 3 digits, then
            // three NULs. The last byte is *not* always zero — the MF level keys carry a value
            // there — so it is deliberately not asserted.
            assert!(key.key_id[..7].iter().all(u8::is_ascii_digit));
            assert_eq!(&key.key_id[7..9], &[0x08, 0x05]);
            assert!(key.key_id[9..12].iter().all(u8::is_ascii_digit));
            assert_eq!(&key.key_id[12..15], &[0, 0, 0]);
        }
    }

    #[test]
    fn lookup_matches_the_whole_identifier() {
        let bytes = *KNOWN[0].key_id;
        let production = KeyId::parse(&bytes).unwrap();
        assert!(find(&production).is_some());

        // The two hierarchies differ only in the first digit, so each must resolve to its own key
        // and never to the other's.
        let mut other = bytes;
        other[0] = b'6';
        let other = KeyId::parse(&other).unwrap();
        assert_ne!(
            find(&other).map(|k| k.modulus),
            find(&production).map(|k| k.modulus)
        );

        // An identifier that is in neither hierarchy resolves to nothing at all.
        let mut absent = bytes;
        absent[0] = b'9';
        assert!(find(&KeyId::parse(&absent).unwrap()).is_none());

        // And the padding counts: two identifiers that differ only there are different keys. The
        // MF level entries really do carry a non-zero byte there, so this is not hypothetical.
        let mut padded = bytes;
        padded[15] ^= 0x01;
        assert!(find(&KeyId::parse(&padded).unwrap()).is_none());
    }

    #[test]
    fn no_two_entries_share_a_key_or_an_identifier() {
        for (i, a) in KNOWN.iter().enumerate() {
            for b in &KNOWN[i + 1..] {
                assert_ne!(a.key_id, b.key_id, "duplicate 証明者鍵ID {}", a.name());
                assert_ne!(
                    a.modulus,
                    b.modulus,
                    "{} and {} share a key",
                    a.name(),
                    b.name()
                );
            }
        }
    }

    #[test]
    fn both_hierarchies_are_present() {
        // x000023 signs 券面事項確認AP certificates, x000033 signs 券面入力補助AP ones, and
        // 6000020 signs the intermediate of the chain reachable at the MF level.
        for name in ["5000023", "5000033", "6000020", "6000023", "6000033"] {
            assert!(KNOWN.iter().any(|k| k.name() == name), "missing {name}");
        }
    }
}
